/**
 * Filter places by category
 */
export function filterByCategory(category) {
  if (category === 'All') return NASHIK_PLACES;
  return NASHIK_PLACES.filter(p => p.category === category);
}

/**
 * Search places by query (name, category, tags, description)
 */
export function searchPlaces(query) {
  if (!query || query.trim() === '') return NASHIK_PLACES;
  const q = query.toLowerCase().trim();
  return NASHIK_PLACES.filter(p =>
    p.name.toLowerCase().includes(q) ||
    p.category.toLowerCase().includes(q) ||
    (p.subcategory && p.subcategory.toLowerCase().includes(q)) ||
    (p.short_description && p.short_description.toLowerCase().includes(q)) ||
    (p.tags && p.tags.some(tag => tag.toLowerCase().includes(q))) ||
    (p.city && p.city.toLowerCase().includes(q))
  );
}

/**
 * Find a place by ID
 */
export function getPlaceById(id) {
  return NASHIK_PLACES.find(p => p.id === id) || null;
}

/**
 * Get nearby places to a given place (by simple distance)
 */
export function getNearbyPlaces(placeId, limit = 5) {
  const place = getPlaceById(placeId);
  if (!place) return [];

  return NASHIK_PLACES
    .filter(p => p.id !== placeId)
    .map(p => ({
      ...p,
      _dist: haversine(place.latitude, place.longitude, p.latitude, p.longitude),
    }))
    .sort((a, b) => a._dist - b._dist)
    .slice(0, limit);
}

/**
 * Get top-rated places for highlights
 */
export function getHighlights(limit = 6) {
  return [...NASHIK_PLACES]
    .sort((a, b) => b.rating - a.rating)
    .slice(0, limit);
}

/**
 * Haversine distance between two lat/lng points (in km)
 */
export function haversine(lat1, lon1, lat2, lon2) {
  const R = 6371;
  const dLat = toRad(lat2 - lat1);
  const dLon = toRad(lon2 - lon1);
  const a = Math.sin(dLat / 2) ** 2 +
    Math.cos(toRad(lat1)) * Math.cos(toRad(lat2)) * Math.sin(dLon / 2) ** 2;
  return R * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
}

function toRad(deg) {
  return deg * (Math.PI / 180);
}
